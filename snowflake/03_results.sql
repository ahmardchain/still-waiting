-- STILL WAITING — Final aggregate results for the web story.
-- Each result can be downloaded as CSV from the Snowflake results panel.

USE WAREHOUSE STILL_WAITING_WH;
USE DATABASE STILL_WAITING;
USE SCHEMA ANALYTICS;

-- Headline metric
SELECT
  COUNT(*) AS DOG_STAYS,
  ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS,
  ROUND(AVG(WAIT_DAYS), 1) AS AVERAGE_WAIT_DAYS
FROM ANALYSIS_DOG_STAYS;

-- Age chart
SELECT
  AGE_BAND,
  COUNT(*) AS DOG_STAYS,
  ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS
FROM ANALYSIS_DOG_STAYS
GROUP BY AGE_BAND
ORDER BY CASE AGE_BAND
  WHEN 'Puppy' THEN 1
  WHEN 'Young' THEN 2
  WHEN 'Adult' THEN 3
  WHEN 'Senior' THEN 4
  ELSE 5
END;

-- Annual trend
SELECT
  YEAR(INTAKE_AT) AS INTAKE_YEAR,
  COUNT(*) AS DOG_STAYS,
  ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS
FROM ANALYSIS_DOG_STAYS
GROUP BY INTAKE_YEAR
ORDER BY INTAKE_YEAR;

-- Intake comparison
SELECT
  INTAKE_TYPE,
  COUNT(*) AS DOG_STAYS,
  ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS
FROM ANALYSIS_DOG_STAYS
GROUP BY INTAKE_TYPE
HAVING COUNT(*) >= 50
ORDER BY MEDIAN_WAIT_DAYS DESC;

-- Outcome context
SELECT
  OUTCOME_TYPE,
  COUNT(*) AS DOG_STAYS,
  ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS
FROM ANALYSIS_DOG_STAYS
GROUP BY OUTCOME_TYPE
ORDER BY DOG_STAYS DESC;

ALTER WAREHOUSE STILL_WAITING_WH SUSPEND;
