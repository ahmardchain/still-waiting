-- STILL WAITING — Final aggregate results for the web story.
-- Each result can be downloaded as CSV from the Snowflake results panel.

USE WAREHOUSE STILL_WAITING_WH;
USE DATABASE STILL_WAITING;
USE SCHEMA ANALYTICS;

-- Headline metric
SELECT
  COUNT(*) AS DOG_STAYS,
  ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS,
  ROUND(AVG(WAIT_DAYS), 1) AS AVERAGE_WAIT_DAYS
FROM ANALYSIS_DOG_STAYS;

-- Age chart
SELECT
  AGE_BAND,
  COUNT(*) AS DOG_STAYS,
  ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS
FROM ANALYSIS_DOG_STAYS
GROUP BY AGE_BAND
ORDER BY CASE AGE_BAND
  WHEN 'Puppy' THEN 1
  WHEN 'Young' THEN 2
  WHEN 'Adult' THEN 3
  WHEN 'Senior' THEN 4
  ELSE 5
END;

-- Annual trend
SELECT
  YEAR(INTAKE_AT) AS INTAKE_YEAR,
  COUNT(*) AS DOG_STAYS,
  ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS
FROM ANALYSIS_DOG_STAYS
GROUP BY INTAKE_YEAR
ORDER BY INTAKE_YEAR;

-- Intake comparison
SELECT
  INTAKE_TYPE,
  COUNT(*) AS DOG_STAYS,
  ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS
FROM ANALYSIS_DOG_STAYS
GROUP BY INTAKE_TYPE
HAVING COUNT(*) >= 50
ORDER BY MEDIAN_WAIT_DAYS DESC;

-- Outcome context
SELECT
  OUTCOME_TYPE,
  COUNT(*) AS DOG_STAYS,
  ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS
FROM ANALYSIS_DOG_STAYS
GROUP BY OUTCOME_TYPE
ORDER BY DOG_STAYS DESC;

-- Complete aggregate cube used by the interactive web explorer.
-- Download this result as CSV; no animal-level records are exported.
WITH BASE AS (
  SELECT
    YEAR(INTAKE_AT) AS INTAKE_YEAR,
    AGE_BAND,
    CASE
      WHEN UPPER(TRIM(INTAKE_TYPE)) = 'STRAY' THEN 'Stray'
      WHEN UPPER(TRIM(INTAKE_TYPE)) = 'OWNER SURRENDER' THEN 'Owner surrender'
      ELSE 'Other'
    END AS INTAKE_GROUP,
    WAIT_DAYS
  FROM ANALYSIS_DOG_STAYS
),
DASHBOARD_CUBE AS (
  SELECT
    IFF(GROUPING(INTAKE_YEAR) = 1, 'All', TO_VARCHAR(INTAKE_YEAR)) AS YEAR_FILTER,
    IFF(GROUPING(AGE_BAND) = 1, 'All dogs', AGE_BAND) AS AGE_FILTER,
    IFF(
      GROUPING(INTAKE_GROUP) = 1,
      'All intake types',
      INTAKE_GROUP
    ) AS INTAKE_FILTER,
    COUNT(*) AS DOG_STAYS,
    ROUND(MEDIAN(WAIT_DAYS), 1) AS MEDIAN_WAIT_DAYS,
    ROUND(AVG(WAIT_DAYS), 1) AS AVERAGE_WAIT_DAYS
  FROM BASE
  GROUP BY GROUPING SETS (
    (),
    (INTAKE_YEAR),
    (AGE_BAND),
    (INTAKE_GROUP),
    (AGE_BAND, INTAKE_GROUP),
    (INTAKE_YEAR, AGE_BAND),
    (INTAKE_YEAR, INTAKE_GROUP),
    (INTAKE_YEAR, AGE_BAND, INTAKE_GROUP)
  )
)
SELECT *
FROM DASHBOARD_CUBE
ORDER BY
  IFF(YEAR_FILTER = 'All', 0, 1),
  TRY_TO_NUMBER(YEAR_FILTER),
  AGE_FILTER,
  INTAKE_FILTER;

ALTER WAREHOUSE STILL_WAITING_WH SUSPEND;
